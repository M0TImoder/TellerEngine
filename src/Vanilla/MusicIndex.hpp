// Original: caster_load / scr_getmusindex
// 対応が無ければ空
inline constexpr std::string_view MusicAsset(std::string_view path) {
    const auto found = std::lower_bound(
        kMusicIndex.begin(), kMusicIndex.end(), path,
        [](const MusicEntry &entry, std::string_view value) { return entry.first < value; });
    if (found == kMusicIndex.end() || found->first != path) {
        return {};
    }
    return found->second;
}

